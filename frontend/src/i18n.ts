import { ref, computed } from 'vue'

/**
 * Supported interface languages.
 */
export type Lang = 'zh' | 'en'

/**
 * Current active language reactively tracked.
 *
 * TD-11: This is a module-level singleton, intentionally shared across all
 * components so that a single `setLang()` call updates the entire UI at once.
 * In unit tests Vitest isolates each test file in its own worker (fresh module
 * registry), and within a file tests reset state via `beforeEach(() => setLang('zh'))`.
 * Migrating to inject/provide would require passing `lang` through every component
 * tree and offers no practical benefit for the current testing setup.
 */
export const lang = ref<Lang>((localStorage.getItem('lang') as Lang) || 'zh')

/**
 * Updates the active language and persists it to local storage.
 * @param {Lang} l - The new language to set.
 */
export const setLang = (l: Lang) => {
  lang.value = l
  localStorage.setItem('lang', l)
}

